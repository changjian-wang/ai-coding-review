const { buildSync } = require('esbuild');
const { readFileSync, existsSync, writeFileSync } = require('node:fs');
const { join, resolve } = require('node:path');

const root = resolve(__dirname, '..', '..', '..');
const result = buildSync({
  absWorkingDir: root,
  entryPoints: [join(__dirname, 'markdown.cjs')],
  outfile: join(__dirname, 'markdown.bundle.js'),
  bundle: true,
  format: 'iife',
  globalName: 'ReviewMarkdown',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'inline',
  metafile: true,
  write: false,
});
const packages = [...new Set(Object.keys(result.metafile.inputs)
  .map((input) => /^node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input)?.[1])
  .filter(Boolean))].sort();
const licenses = packages.map((name) => {
  const directory = join(root, 'node_modules', ...name.split('/'));
  const metadata = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt', 'license', 'license.md']
    .map((file) => join(directory, file)).find((file) => existsSync(file));
  if (!license) throw new Error(`Missing bundled dependency license: ${name}`);
  return `/*!\n${metadata.name} ${metadata.version}\n${readFileSync(license, 'utf8').replace(/\*\//g, '* /')}\n*/`;
});
const output = `/* Generated by build-markdown.cjs; edit markdown.cjs instead. */\n${licenses.join('\n')}\n${result.outputFiles[0].text}`;
writeFileSync(join(__dirname, 'markdown.bundle.js'), output);
console.log(`Built offline Markdown renderer: ${Buffer.byteLength(output)} bytes, ${packages.length} dependency licenses included.`);
